"""Offline Ragas 0.4.3 evaluation for the BNS Qwen/Ollama RAG application.

Only reads eval_results/runs.jsonl generated by ``evaluate_rag.py collect``.
Does NOT index/re-embed data, run retrieval, or generate new chatbot answers.

Dependencies installed in your permitted evaluation environment:
    ragas==0.4.3, langchain-community==0.3.31, openai, httpx

Examples from RAG_project folder:
    python ragas_score.py --limit 1 --metric faithfulness
    python ragas_score.py --limit 3 --timeout 1800
    python ragas_score.py --limit 1 --timeout 0  # disable request read timeout
    python ragas_score.py --probe               # direct, short Ollama check
"""
from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import math
import statistics
import sys
import time
from pathlib import Path
from typing import Any, Callable
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parent
METRIC_NAMES = (
    "faithfulness",
    "answer_relevancy",
    "context_precision",
    "context_recall",
    "answer_completeness_recall",
)


def load_jsonl(path: Path, *, required: bool = True) -> list[dict[str, Any]]:
    if not path.is_file():
        if required:
            raise FileNotFoundError(f"Missing {path}. Run 'evaluate_rag.py collect' first.")
        return []
    rows: list[dict[str, Any]] = []
    for line_no, raw in enumerate(path.read_text(encoding="utf-8-sig").splitlines(), 1):
        if not raw.strip():
            continue
        try:
            value = json.loads(raw)
        except json.JSONDecodeError as exc:
            raise ValueError(f"Invalid JSON in {path} at line {line_no}: {exc}") from exc
        if not isinstance(value, dict):
            raise ValueError(f"Expected JSON object in {path} at line {line_no}")
        rows.append(value)
    return rows


def reference_from_facts(run: dict[str, Any]) -> str:
    facts = run.get("required_facts") or []
    return "\n".join(f"{i}. {fact}" for i, fact in enumerate(facts, 1))


def contexts_from_run(run: dict[str, Any]) -> list[str]:
    # Only selected evidence; no re-query or mutation of Qdrant.
    return [str(chunk.get("text", "")).strip()
            for chunk in (run.get("chunks") or [])
            if str(chunk.get("text", "")).strip()]


def section_recall(run: dict[str, Any]) -> float | None:
    try:
        expected = {int(s) for s in run.get("expected_sections", [])}
    except (TypeError, ValueError) as exc:
        raise ValueError(f"Invalid expected_sections for {run.get('id')}: {exc}") from exc
    if not expected:
        return None
    seen: set[int] = set()
    for chunk in run.get("chunks") or []:
        try:
            seen.add(int(chunk.get("section_number")))
        except (ValueError, TypeError):
            continue
    return len(expected & seen) / len(expected)


def metric_value(result: Any) -> float:
    value = float(result.value)
    if not math.isfinite(value):
        raise ValueError(f"Ragas returned non-finite score: {value}")
    return round(value, 5)


def fingerprint(run: dict[str, Any], args: argparse.Namespace) -> str:
    """Avoid reusing past scores after input, judge, or relevant settings change."""
    content = {
        "version": 2,
        "question": run.get("question"),
        "answer": run.get("answer"),
        "answerable": run.get("answerable"),
        "contexts": contexts_from_run(run),
        "reference": reference_from_facts(run),
        "expected_sections": run.get("expected_sections"),
        "judge_model": args.judge_model,
        "embedding_model": args.embedding_model,
        "thinking": args.thinking,
        "max_tokens": args.max_tokens,
        "temperature": args.temperature,
    }
    serialized = json.dumps(content, sort_keys=True, ensure_ascii=False, default=str)
    return hashlib.sha256(serialized.encode("utf-8")).hexdigest()


def new_record(run: dict[str, Any], input_hash: str) -> dict[str, Any]:
    return {
        "id": run.get("id"),
        "question": run.get("question"),
        "answerable": run.get("answerable", True),
        "selected_sections": run.get("selected_sections", []),
        "section_recall": section_recall(run),
        "input_hash": input_hash,
        "scores": {name: None for name in METRIC_NAMES},
        "errors": {},
        "metric_reasons": {},
        "metric_seconds": {},
    }


def atomic_write_jsonl(path: Path, records: list[dict[str, Any]]) -> None:
    """Save after EACH metric: interruptions won't lose completed scores."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("w", encoding="utf-8") as stream:
        for row in records:
            stream.write(json.dumps(row, ensure_ascii=False, default=str) + "\n")
    temporary.replace(path)


def ollama_models(ollama_url: str) -> set[str]:
    request = Request(ollama_url.rstrip("/") + "/api/tags")
    try:
        with urlopen(request, timeout=12) as response:
            body = json.load(response)
    except (HTTPError, URLError, OSError, TimeoutError) as exc:
        raise RuntimeError(
            f"Ollama is unreachable at {ollama_url}. Start Ollama first. Detail: {exc}"
        ) from exc
    return {str(x.get("name", x.get("model", ""))) for x in body.get("models", [])}


def verify_ollama_models(args: argparse.Namespace, chosen_metrics: list[str]) -> None:
    print("Checking local Ollama server and installed models...", flush=True)
    names = ollama_models(args.ollama_url)
    required = [args.judge_model]
    if "answer_relevancy" in chosen_metrics:
        required.append(args.embedding_model)
    # Ollama reports untagged pulls as :latest, e.g. nomic-embed-text:latest.
    missing = [
        model for model in required
        if model not in names and (":" in model or model + ":latest" not in names)
    ]
    if missing:
        raise RuntimeError(
            f"Ollama model(s) not found: {missing}. Available: {sorted(names)}. "
            "Use 'ollama list' and download approved models before evaluation."
        )
    print(f"  Ollama OK. Judge: {args.judge_model}", flush=True)


def build_metrics(args: argparse.Namespace, chosen_metrics: list[str]) -> tuple[dict[str, Any], Any]:
    print("Importing Ragas, OpenAI async client, and metric classes...", flush=True)
    try:
        import httpx
        from openai import AsyncOpenAI
        from ragas.llms import llm_factory
        from ragas.metrics.collections import (
            Faithfulness, ContextPrecision, ContextRecall, FactualCorrectness,
        )
    except (ImportError, OSError) as exc:
        raise RuntimeError(
            "Could not import Ragas dependencies. Check approved package versions, "
            "including langchain-community==0.3.31, or any company DLL restrictions. "
            f"Underlying error: {type(exc).__name__}: {exc}"
        ) from exc

    # Timeout=0 intentionally disables the request read timeout, but still
    # fails promptly if connecting to localhost is impossible.
    if args.timeout == 0:
        timeout = httpx.Timeout(None, connect=15.0)
        timeout_label = "disabled (connect timeout 15 seconds)"
    else:
        timeout = httpx.Timeout(args.timeout, connect=min(args.timeout, 15.0))
        timeout_label = f"{args.timeout:g} seconds per API request"

    client = AsyncOpenAI(
        api_key="ollama",  # Local API; does NOT contact OpenAI servers.
        base_url=args.ollama_url.rstrip("/") + "/v1",
        timeout=timeout,
        max_retries=0,  # Ragas/instructor may have its own structured-output retries.
    )

    options: dict[str, Any] = {
        "temperature": args.temperature,
        "max_tokens": args.max_tokens,
    }
    if args.thinking == "off":
        # Ollama's OpenAI-compatible endpoint accepts this for Qwen 3.5.
        options["reasoning_effort"] = "none"
    elif args.thinking != "default":
        options["reasoning_effort"] = args.thinking
    try:
        judge = llm_factory(args.judge_model, provider="openai", client=client, **options)
    except Exception:
        # Close client from main_async when available; don't hide the root error.
        raise

    # Trace *individual judge requests* so a 2-call metric is not a black box.
    if not args.quiet_requests:
        original_generate = judge.agenerate
        calls = 0

        async def trace_generate(*call_args: Any, **call_kwargs: Any) -> Any:
            nonlocal calls
            calls += 1
            number = calls
            started = time.perf_counter()
            prompt = call_args[0] if call_args else call_kwargs.get("prompt", "")
            schema = (call_args[1] if len(call_args) > 1
                      else call_kwargs.get("response_model"))
            schema_name = getattr(schema, "__name__", str(schema))
            print(f"    [Judge request {number}] {schema_name}; "
                  f"prompt {len(str(prompt)):,} chars | started", flush=True)
            try:
                response = await original_generate(*call_args, **call_kwargs)
            except Exception as exc:
                print(f"    [Judge request {number}] failed in "
                      f"{time.perf_counter() - started:.1f}s: "
                      f"{type(exc).__name__}: {exc}", flush=True)
                raise
            print(f"    [Judge request {number}] completed in "
                  f"{time.perf_counter() - started:.1f}s", flush=True)
            return response

        judge.agenerate = trace_generate

    classes = {
        "faithfulness": lambda: Faithfulness(llm=judge),
        "context_precision": lambda: ContextPrecision(llm=judge),
        "context_recall": lambda: ContextRecall(llm=judge),
        "answer_completeness_recall": lambda: FactualCorrectness(llm=judge, mode="recall"),
    }
    metrics: dict[str, Any] = {}
    for name in chosen_metrics:
        if name in classes:
            metrics[name] = classes[name]()
        elif name == "answer_relevancy":
            from ragas.embeddings.base import embedding_factory
            from ragas.metrics.collections import AnswerRelevancy
            embeddings = embedding_factory(
                "openai", model=args.embedding_model, client=client, interface="modern"
            )
            metrics[name] = AnswerRelevancy(llm=judge, embeddings=embeddings)
    print(f"Metrics ready: {', '.join(metrics)} | Timeout: {timeout_label} | "
          f"Thinking: {args.thinking}", flush=True)
    return metrics, client


def metric_inputs(run: dict[str, Any]) -> dict[str, dict[str, Any]]:
    question = str(run.get("question", "")).strip()
    answer = str(run.get("answer", "")).strip()
    contexts = contexts_from_run(run)
    reference = reference_from_facts(run)
    return {
        "faithfulness": dict(user_input=question, response=answer,
                             retrieved_contexts=contexts),
        "answer_relevancy": dict(user_input=question, response=answer),
        "context_precision": dict(user_input=question, reference=reference,
                                  retrieved_contexts=contexts),
        "context_recall": dict(user_input=question, reference=reference,
                               retrieved_contexts=contexts),
        "answer_completeness_recall": dict(response=answer, reference=reference),
    }


async def score_one(
    run: dict[str, Any],
    metrics: dict[str, Any],
    record: dict[str, Any],
    *,
    resume: bool = True,
    on_progress: Callable[[dict[str, Any]], None] | None = None,
) -> dict[str, Any]:
    if run.get("error"):
        record["errors"]["collection"] = str(run["error"])
        return record
    if not run.get("answerable", True):
        record["skipped"] = (
            "Unanswerable: evaluate abstention using the existing custom evaluator."
        )
        return record

    question = str(run.get("question", "")).strip()
    answer = str(run.get("answer", "")).strip()
    contexts = contexts_from_run(run)
    if not question or not answer or not contexts:
        record["errors"]["input"] = "Missing question, answer, or retrieved contexts."
        return record
    reference = reference_from_facts(run)
    inputs = metric_inputs(run)
    for name in METRIC_NAMES:
        if name not in metrics:
            continue
        if not reference and name in (
            "context_precision", "context_recall", "answer_completeness_recall"
        ):
            record["errors"][name] = "No required_facts; reference-based score undefined."
            continue
        if resume and record["scores"].get(name) is not None:
            print(f"  {name}: cached {record['scores'][name]:.4f} (skipping)", flush=True)
            continue
        record["errors"].pop(name, None)
        print(f"  START {name} (may make multiple Qwen calls)...", flush=True)
        start = time.perf_counter()
        try:
            # The AsyncOpenAI client must be used with Ragas .ascore(),
            # all inside one event loop.
            result = await metrics[name].ascore(**inputs[name])
            record["scores"][name] = metric_value(result)
            if getattr(result, "reason", None):
                record["metric_reasons"][name] = str(result.reason)
            print(f"  DONE  {name}: {record['scores'][name]:.5f}", flush=True)
        except Exception as exc:
            record["scores"][name] = None
            record["errors"][name] = f"{type(exc).__name__}: {exc}"
            print(f"  FAILED {name}: {record['errors'][name]}", flush=True)
        finally:
            record["metric_seconds"][name] = round(time.perf_counter() - start, 2)
            print(f"  TIME  {name}: {record['metric_seconds'][name]:.1f}s", flush=True)
            if on_progress is not None:
                on_progress(record)
    return record


def summarize(results: list[dict[str, Any]]) -> dict[str, Any]:
    summary: dict[str, Any] = {
        "processed": len(results),
        "metrics": {},
        "cases_with_errors": sum(bool(r.get("errors")) for r in results),
    }
    for name in (*METRIC_NAMES, "section_recall"):
        if name == "section_recall":
            available = [r.get(name) for r in results if r.get(name) is not None]
        else:
            available = [r["scores"].get(name) for r in results
                         if r.get("scores", {}).get(name) is not None]
        summary["metrics"][name] = {
            "mean": round(statistics.mean(available), 4) if available else None,
            "count": len(available),
        }
    return summary


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Evaluate saved BNS RAG runs with Ragas 0.4.3 + local Ollama"
    )
    p.add_argument("--runs", type=Path, default=ROOT / "eval_results" / "runs.jsonl")
    p.add_argument("--output", type=Path,
                   default=ROOT / "eval_results" / "ragas_scores.jsonl")
    p.add_argument("--summary", type=Path,
                   default=ROOT / "eval_results" / "ragas_summary.json")
    p.add_argument("--limit", type=int, default=0,
                   help="Number of saved test cases; 0 means all cases")
    p.add_argument("--metric", choices=METRIC_NAMES, default=None,
                   help="Only evaluate the specified metric")
    p.add_argument("--skip-relevancy", action="store_true",
                   help="Skip answer_relevancy (no nomic-embed-text needed)")
    p.add_argument("--judge-model", default="qwen3.5:4b")
    p.add_argument("--embedding-model", default="nomic-embed-text")
    p.add_argument("--ollama-url", default="http://127.0.0.1:11434")
    p.add_argument("--timeout", type=float, default=1800.0,
                   help="API timeout in seconds (default 1800; 0 disables read timeout)")
    p.add_argument("--thinking", choices=("off", "default", "low", "medium", "high"),
                   default="off", help="Disable Qwen thinking by default for speed")
    p.add_argument("--temperature", type=float, default=0.0)
    p.add_argument("--max-tokens", type=int, default=2048,
                   help="Max output tokens per judge call; avoid truncated JSON")
    p.add_argument("--no-resume", action="store_true",
                   help="Discard previous valid metric results and recompute")
    p.add_argument("--quiet-requests", action="store_true",
                   help="Hide per-request tracing (metric timing still printed)")
    p.add_argument("--no-preflight", action="store_true",
                   help="Skip Ollama availability/model preflight check")
    p.add_argument("--probe", action="store_true",
                   help="Check direct Ollama generation speed; no Ragas metrics or runs file needed")
    return p.parse_args(argv)


def probe_ollama(args: argparse.Namespace) -> None:
    """Optional direct judge speed test, separate from Ragas scoring."""
    print(f"Probing Ollama model {args.judge_model}...", flush=True)
    payload = {
        "model": args.judge_model,
        "messages": [{"role": "user", "content": 'Return only this JSON: {"ok":true}'}],
        "stream": False,
        "think": args.thinking != "off",
        "format": "json",
        "options": {"temperature": 0, "num_predict": 80, "num_ctx": 2048},
    }
    data = json.dumps(payload).encode("utf-8")
    request = Request(
        args.ollama_url.rstrip("/") + "/api/chat",
        data=data,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    started = time.perf_counter()
    try:
        with urlopen(request, timeout=(None if args.timeout == 0 else args.timeout)) as response:
            result = json.load(response)
    except (HTTPError, URLError, OSError, TimeoutError) as exc:
        raise RuntimeError(f"Ollama probe failed: {exc}") from exc
    print(f"Probe completed in {time.perf_counter() - started:.1f}s", flush=True)
    print(f"  Response: {str(result.get('message', {}).get('content', ''))[:500]}")
    print(f"  Input tokens: {result.get('prompt_eval_count', 'unknown')}")
    print(f"  Output tokens: {result.get('eval_count', 'unknown')}")


async def main_async(argv: list[str] | None = None) -> None:
    args = parse_args(argv)
    if args.limit < 0 or args.timeout < 0 or args.max_tokens <= 0:
        raise ValueError("--limit and --timeout must be >=0; --max-tokens must be >0")
    if not (0 <= args.temperature <= 2):
        raise ValueError("--temperature should be between 0 and 2")
    if args.skip_relevancy and args.metric == "answer_relevancy":
        raise ValueError("Can't use --metric answer_relevancy and --skip-relevancy together")
    if args.probe:
        probe_ollama(args)
        return
    runs = load_jsonl(args.runs)
    if args.limit:
        runs = runs[:args.limit]
    if not runs:
        raise ValueError("No evaluation runs found")
    chosen = ([args.metric] if args.metric else
              [name for name in METRIC_NAMES
               if not (args.skip_relevancy and name == "answer_relevancy")])

    if not args.no_preflight:
        verify_ollama_models(args, chosen)
    metrics, client = build_metrics(args, chosen)
    print(f"\nScoring {len(runs)} saved case(s); metrics: {', '.join(chosen)}", flush=True)
    # Preserve results from earlier cases outside the current --limit selection.
    old_results = {
        str(row.get("id")): row for row in load_jsonl(args.output, required=False)
        if row.get("id") is not None
    }
    results: list[dict[str, Any]] = []
    started = time.perf_counter()
    try:
        for index, run in enumerate(runs, 1):
            key = str(run.get("id"))
            print(f"\n[{index}/{len(runs)}] Ragas: {key}", flush=True)
            h = fingerprint(run, args)
            old = old_results.get(key)
            if old and old.get("input_hash") == h and not args.no_resume:
                record = old
                for field in ("scores", "errors", "metric_reasons", "metric_seconds"):
                    record.setdefault(field, {})
                for name in METRIC_NAMES:
                    record["scores"].setdefault(name, None)
            else:
                record = new_record(run, h)

            def save(current: dict[str, Any]) -> None:
                old_results[key] = current
                atomic_write_jsonl(args.output, list(old_results.values()))

            result = await score_one(
                run, metrics, record,
                resume=not args.no_resume,
                on_progress=save,
            )
            results.append(result)
            save(result)  # Also save input failures and unanswerable cases.
    finally:
        await client.close()
    overall = summarize(results)
    overall["elapsed_seconds"] = round(time.perf_counter() - started, 2)
    overall["judge_model"] = args.judge_model
    overall["metrics_requested"] = chosen
    args.summary.parent.mkdir(parents=True, exist_ok=True)
    args.summary.write_text(json.dumps(overall, ensure_ascii=False, indent=2), encoding="utf-8")
    print("\nAVERAGE SCORES (N/A = not assessed)")
    for name, data in overall["metrics"].items():
        mean = "N/A" if data["mean"] is None else f"{data['mean']:.3f}"
        print(f"  {name:28} {mean:>7}  n={data['count']}")
    print(f"\nSaved: {args.output}\nSummary: {args.summary}", flush=True)


def main(argv: list[str] | None = None) -> None:
    asyncio.run(main_async(argv))


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\nInterrupted. Metrics completed before interruption are checkpointed.",
              file=sys.stderr)
        sys.exit(130)
    except (ValueError, FileNotFoundError, RuntimeError) as exc:
        print(f"ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        sys.exit(1)
